def provision(directory, project, private_root, socket_root, enrollment=None, kind='domain', compose_name='docker-compose.yml'):
    import yaml
    from services.system_update_runtime import write_json
    path=Path(directory).resolve();root=Path(private_root).resolve();sockets=Path(socket_root).resolve()
    if not re.fullmatch(r'[a-z0-9][a-z0-9_-]{0,62}',project): raise ValueError('Invalid project')
    if kind not in ('domain','local'): raise ValueError('Invalid installation kind')
    if root.is_relative_to(path) or root == sockets or sockets.is_relative_to(path):
        raise ValueError('Controller state and socket must be outside tenant storage')
    if compose_name not in ('docker-compose.yml','docker-compose.production.yml'): raise ValueError('Unsupported Compose filename')
    compose=path/compose_name
    data=yaml.safe_load(compose.read_text(encoding='utf-8'));services=data['services']
    if 'update_controller' in services: raise ValueError('Controller already configured; do not replay creation')
    # Creation receipts are generated by the OLD panel before the first startup.
    for filename in ('_panel_create_failed.json','update-controller-provisioned.json'):
        if (path/filename).exists(): raise ValueError('Existing deployment requires an explicit enrollment procedure')
    roles={'web':'web','core':'radius_core','db':'db'} if kind=='domain' else {'web':'wisp-web','core':'freeradius','db':'mariadb'}
    if not set(roles.values()) <= set(services): raise ValueError('Unsupported Compose service layout')
    web=services[roles['web']];image=web['image']
    if not re.fullmatch(r'mohd777/max-radius-web@sha256:[0-9a-f]{64}',image):
        raise ValueError('Pin the Web Registry digest before provisioning')
    if root.exists() and any(root.iterdir()): raise ValueError('Private controller root already initialized')
    root.mkdir(mode=0o700,parents=True,exist_ok=True);sockets.mkdir(mode=0o750,parents=True,exist_ok=True)
    mounts=[{'Type':'bind','Source':str(root),'Target':'/max-update-private','ReadOnly':False},
            {'Type':'bind','Source':'/var/run/docker.sock','Target':'/var/run/docker.sock','ReadOnly':False},
            {'Type':'bind','Source':str(path),'Target':'/max-update-compose','ReadOnly':False}]
    config=dict(TRUST,channel='https://control.max-net.net',kind='public',executor='host' if kind=='domain' else 'local',
                project=project,services=roles,compose_path='/max-update-compose/'+compose_name,controller_mounts=mounts)
    if enrollment:
        allowed={'kind','identity','reader_id','token'}
        if set(enrollment) != allowed or enrollment['kind'] != kind or not all(enrollment.values()):
            raise ValueError('Invalid protected enrollment record')
        config.update(enrollment)
    write_json(root/'update-channel.private.json',config)
    services['update_controller']={
        'image':image,'restart':'unless-stopped','read_only':True,
        'entrypoint':['python','-c'],
        'command':['import sys;from services.system_update_host import main;sys.argv=["controller","/max-update-private","/max-update-socket/controller.sock"];main()'],
        'environment':{'PYTHONDONTWRITEBYTECODE':'1'},'tmpfs':['/tmp:rw,nosuid,size=32m'],
        'volumes':[str(root)+':/max-update-private', '/var/run/docker.sock:/var/run/docker.sock',
                   str(path)+':/max-update-compose',str(sockets)+':/max-update-socket'],
        'healthcheck':{'test':['CMD','python','-c','import socket;s=socket.socket(socket.AF_UNIX);s.settimeout(2);s.connect("/max-update-socket/controller.sock");s.close()'],
                       'interval':'10s','timeout':'3s','retries':3}}
    web.setdefault('volumes',[]).append(str(sockets)+':/max-update-socket:ro')
    env=web.setdefault('environment',{})
    if isinstance(env,list):
        if any(not isinstance(v,str) or '=' not in v for v in env): raise ValueError('Resolve the Web environment before enrollment')
        env=dict(v.split('=',1) for v in env);web['environment']=env
    if not isinstance(env,dict): raise ValueError('Use a mapping for Web environment')
    env['MAX_UPDATE_SOCKET']='/max-update-socket/controller.sock'
    dependencies=web.setdefault('depends_on',{})
    if isinstance(dependencies,list):
        dependencies={v:{'condition':'service_started'} for v in dependencies};web['depends_on']=dependencies
    dependencies['update_controller']={'condition':'service_started'}
    # Preserve the original JSON/YAML and all existing service definitions.
    (root/'compose-before-enrollment.private').write_bytes(compose.read_bytes())
    raw=yaml.safe_dump(data,sort_keys=False,allow_unicode=True).encode('utf-8')
    temp=compose.with_name('.compose-update-provision.tmp')
    with temp.open('wb') as out:
        os.chmod(temp,0o600);out.write(raw);out.flush();os.fsync(out.fileno())
    os.replace(temp,compose)
    write_json(path/'update-controller-provisioned.json',{'project':project,'kind':config['kind'],
                'targeted_enrollment':bool(enrollment),'image':image,'key_fingerprint':TRUST['key_fingerprint']})
    return {'provisioned':True,'targeted_enrollment':bool(enrollment),'private_key_included':False}
